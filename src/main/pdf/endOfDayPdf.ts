import * as path from 'path';
import { EndOfDayReport } from '../../shared/types/domain';
import { getAppPaths } from '../utils/paths';
import { formatPdfMoney, writePdf } from './pdfService';

/**
 * End of Day report PDF — A4, saved into Documents/POS Reports/End Of Day/.
 * Generated at every End of Day, alongside the database backup.
 */
export interface EndOfDayPdfData {
  report: EndOfDayReport;
  businessName: string;
  currencySymbol: string;
  /** Local ISO timestamp of when the report was produced. */
  generatedAt: string;
}

const PAGE_WIDTH = 595.28; // A4 portrait, points
const PAGE_HEIGHT = 841.89;
const MARGIN = 56;
const CONTENT_WIDTH = PAGE_WIDTH - MARGIN * 2;
const DIVIDER = '─'.repeat(64);

export async function generateEndOfDayPdf(data: EndOfDayPdfData): Promise<string> {
  const { endOfDayReportsDir } = getAppPaths();
  const { report } = data;
  const fileName = `EndOfDay_${report.businessDate}_${fileSafeTimepart()}.pdf`;
  const filePath = path.join(endOfDayReportsDir, fileName);

  await writePdf(filePath, PAGE_WIDTH, PAGE_HEIGHT, (doc) => {
    const money = (cents: number): string => formatPdfMoney(cents, data.currencySymbol);
    let y = MARGIN;

    const divider = (): void => {
      y += 10;
      doc
        .font('Helvetica')
        .fontSize(8)
        .fillColor('#999999')
        .text(DIVIDER, MARGIN, y, { width: CONTENT_WIDTH });
      doc.fillColor('#000000');
      y += 18;
    };

    const metricRow = (label: string, value: string, bold = false): void => {
      const font = bold ? 'Helvetica-Bold' : 'Helvetica';
      doc.font(font).fontSize(10).text(label, MARGIN, y, { width: CONTENT_WIDTH - 160 });
      doc.font(font).fontSize(10).text(value, MARGIN, y, {
        width: CONTENT_WIDTH,
        align: 'right'
      });
      y += 18;
    };

    // Header
    doc.font('Helvetica-Bold').fontSize(14).text(data.businessName, MARGIN, y, {
      width: CONTENT_WIDTH
    });
    y += 24;
    doc.font('Helvetica-Bold').fontSize(20).text('End of Day Report', MARGIN, y, {
      width: CONTENT_WIDTH
    });
    y += 24;
    doc
      .font('Helvetica')
      .fontSize(10)
      .text(`Business date: ${report.businessDate}`, MARGIN, y, { width: CONTENT_WIDTH });
    y += 16;
    doc.text(
      `Generated: ${data.generatedAt.slice(0, 10)} ${data.generatedAt.slice(11, 19)}`,
      MARGIN,
      y,
      { width: CONTENT_WIDTH }
    );
    divider();

    // Financial summary
    doc.font('Helvetica-Bold').fontSize(12).text('Financial summary', MARGIN, y, {
      width: CONTENT_WIDTH
    });
    y += 22;
    metricRow('Gross Sales', money(report.grossSalesCents));
    metricRow('Cost of Goods Sold', money(report.costOfGoodsSoldCents));
    metricRow('Gross Profit', money(report.grossProfitCents), true);
    metricRow(`VAT (included in sales)`, money(report.vatTotalCents));
    divider();

    // Activity
    doc.font('Helvetica-Bold').fontSize(12).text('Activity', MARGIN, y, {
      width: CONTENT_WIDTH
    });
    y += 22;
    metricRow('Transactions', String(report.transactionCount));
    metricRow('Average sale', money(report.averageSaleCents));
    metricRow(`Voids (${report.voidCount})`, money(report.voidTotalCents));
    divider();

    // Top sellers
    doc.font('Helvetica-Bold').fontSize(12).text('Top selling products', MARGIN, y, {
      width: CONTENT_WIDTH
    });
    y += 22;

    if (report.topProducts.length === 0) {
      doc.font('Helvetica').fontSize(10).text('No sales recorded for this business day.', MARGIN, y, {
        width: CONTENT_WIDTH
      });
      y += 18;
    } else {
      report.topProducts.forEach((product, index) => {
        doc
          .font('Helvetica')
          .fontSize(10)
          .text(`${index + 1}. ${product.productName}`, MARGIN, y, { width: CONTENT_WIDTH - 220 });
        doc.text(`${product.quantitySold} sold`, MARGIN + CONTENT_WIDTH - 220, y, {
          width: 110
        });
        doc.text(money(product.grossCents), MARGIN, y, {
          width: CONTENT_WIDTH,
          align: 'right'
        });
        y += 18;
      });
    }
    divider();

    // Footer
    doc
      .font('Helvetica')
      .fontSize(8)
      .fillColor('#777777')
      .text('Generated by ManaPOS', MARGIN, y, { width: CONTENT_WIDTH, align: 'center' });
  });

  return filePath;
}

function fileSafeTimepart(now: Date = new Date()): string {
  const pad = (n: number): string => String(n).padStart(2, '0');
  return `${pad(now.getHours())}${pad(now.getMinutes())}${pad(now.getSeconds())}`;
}
